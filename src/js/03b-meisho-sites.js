// 建物ごとの置き場所（実寸の x, y）を決める。名所の中心からの隔たりを F 倍に広げる
for (const m of MEISHO) {
  const [ax, ay] = ll(...m.anchor);
  m.ax = ax;
  m.ay = ay;
  for (const p of m.parts) {
    const [x, y] = ll(...p.at);
    p.x = ax + (x - ax) * m.F;
    p.y = ay + (y - ay) * m.F;
    if (p.fp) {
      // 商業施設：輪郭の広がり（作品の中の長さ）と、まわりの駐車場の分
      let x0 = 1e9,
        x1 = -1e9,
        y0 = 1e9,
        y1 = -1e9;
      for (const q of p.fp) {
        const [qx, qy] = ll(...q);
        (x0 = Math.min(x0, qx)), (x1 = Math.max(x1, qx)), (y0 = Math.min(y0, qy)), (y1 = Math.max(y1, qy));
      }
      p.w = (x1 - x0) * p.sc + 30;
      p.d = (y1 - y0) * p.sc + 30;
    }
    p.r = (Math.hypot(p.w, p.d) / 2 + 4) / S; // まわりをどける半径（実寸m。建物の対角の半分と、木の大きさの分）
  }
}
// 名所の建物の上か（木や家を置かない）
function meishoClear(x, y) {
  for (const m of MEISHO)
    if (Math.abs(x - m.ax) < 1500 && Math.abs(y - m.ay) < 1500)
      for (const p of m.parts) if ((x - p.x) ** 2 + (y - p.y) ** 2 < p.r * p.r) return true;
  return false;
}
